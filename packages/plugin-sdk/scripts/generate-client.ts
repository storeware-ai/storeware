import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * Writes the typed API client in `src/generated/` from the public API's
 * OpenAPI document, `apps/api/openapi/v1.json`.
 *
 * Run it with `pnpm --filter @storeware/plugin-sdk generate` after the API's
 * document changes. `src/generated/generated.drift.test.ts` runs the same
 * generator in memory and fails when the committed files say something else,
 * so a route that changed without a regenerate is a red test, not a client
 * that quietly sends the wrong shape.
 *
 * The output is types and one small dispatcher, nothing more. Every request
 * goes through the SDK's own `StorewareClient`, which already owns the token,
 * its rotation and the error type; this only knows where each operation lives
 * and what it sends and answers.
 *
 * The generator is pure (`generateClient` takes the parsed document and
 * returns file contents) and then prettier formats what it wrote with the
 * repository's own settings. Formatting with prettier, rather than emitting
 * text that happens to look formatted, is what keeps `pnpm format` from ever
 * rewriting these files: the drift test compares against prettier's output,
 * and prettier's output is stable under prettier.
 */

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
export const PACKAGE_DIR = resolve(SCRIPT_DIR, '..');
export const DOCUMENT_PATH = resolve(PACKAGE_DIR, '../../apps/api/openapi/v1.json');
export const OUTPUT_DIR = join(PACKAGE_DIR, 'src/generated');
export const REGENERATE = 'pnpm --filter @storeware/plugin-sdk generate';

const HEADER = [
  '// Generated by packages/plugin-sdk/scripts/generate-client.ts from',
  '// apps/api/openapi/v1.json. Do not edit by hand: change the API, then run',
  `// \`${REGENERATE}\`.`,
  '',
].join('\n');

/** A JSON Schema as OpenAPI 3.1 writes one. Only what the generator reads is named. */
export interface Schema {
  $ref?: string;
  type?: string | string[];
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: boolean | Schema;
  items?: Schema;
  enum?: unknown[];
  const?: unknown;
  anyOf?: Schema[];
  oneOf?: Schema[];
  allOf?: Schema[];
  not?: Schema;
  nullable?: boolean;
  description?: string;
  deprecated?: boolean;
  [keyword: string]: unknown;
}

interface Parameter {
  name: string;
  in: string;
  required?: boolean;
  description?: string;
  schema?: Schema;
}

interface Operation {
  operationId?: string;
  summary?: string;
  description?: string;
  deprecated?: boolean;
  'x-storeware-scopes'?: string[];
  parameters?: Parameter[];
  requestBody?: { required?: boolean; content?: Record<string, { schema?: Schema }> };
  responses?: Record<string, { content?: Record<string, { schema?: Schema }> }>;
}

export interface OpenApiDocument {
  openapi: string;
  paths: Record<string, Record<string, Operation>>;
  components?: { schemas?: Record<string, Schema> };
}

/**
 * Keywords that narrow a value without changing its TypeScript type. A length
 * or a pattern has no type to become, so they are read past; anything not on
 * this list stops the generator, because a keyword it does not understand is
 * a type it would get wrong.
 */
const ANNOTATIONS = new Set([
  'description',
  'title',
  'format',
  'default',
  'example',
  'examples',
  'deprecated',
  'readOnly',
  'writeOnly',
  'minLength',
  'maxLength',
  'pattern',
  'minimum',
  'maximum',
  'exclusiveMinimum',
  'exclusiveMaximum',
  'multipleOf',
  'minItems',
  'maxItems',
  'uniqueItems',
  'minProperties',
  'maxProperties',
  // Object keys are strings in TypeScript already.
  'propertyNames',
]);

const UNDERSTOOD = new Set([
  ...ANNOTATIONS,
  '$ref',
  'type',
  'properties',
  'required',
  'additionalProperties',
  'items',
  'enum',
  'const',
  'anyOf',
  'oneOf',
  'allOf',
  'not',
  'nullable',
]);

const METHODS = ['get', 'post', 'put', 'patch', 'delete'] as const;
type Method = (typeof METHODS)[number];

const SCHEMA_REF = '#/components/schemas/';
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

function pascal(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

function propertyKey(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

/** Comment text wraps here, so a long description reads without scrolling sideways. */
const WRAP = 80;

function wrap(line: string): string[] {
  const lines: string[] = [];
  let current = '';
  for (const word of line.split(' ')) {
    if (current && current.length + 1 + word.length > WRAP) {
      lines.push(current);
      current = word;
    } else {
      current = current ? `${current} ${word}` : word;
    }
  }
  lines.push(current);
  return lines;
}

/** A doc comment, or nothing. `*\/` inside the text would end the comment early. */
function doc(...paragraphs: (string | undefined)[]): string {
  const text = paragraphs
    .filter((paragraph): paragraph is string => Boolean(paragraph?.trim()))
    .map((paragraph) => paragraph.trim().replaceAll('*/', '*\\/'))
    .join('\n\n');
  if (!text) return '';
  const lines = text.split('\n').flatMap((line) => (line ? wrap(line) : ['']));
  if (lines.length === 1) return `/** ${lines[0]} */\n`;
  return `/**\n${lines.map((line) => (line ? ` * ${line}` : ' *')).join('\n')}\n */\n`;
}

function union(members: string[]): string {
  const unique = [...new Set(members)];
  if (unique.includes('unknown')) return 'unknown';
  return unique.length === 0 ? 'never' : unique.join(' | ');
}

/** Wraps a union or intersection so it can be followed by `[]`. */
function grouped(type: string): string {
  return /[|&]/.test(type) && !/^[{(]/.test(type) ? `(${type})` : type;
}

class Emitter {
  /** Component names referenced by what this emitter has written, for its imports. */
  readonly refs = new Set<string>();

  constructor(
    private readonly components: Record<string, Schema>,
    private readonly where: string,
  ) {}

  type(schema: Schema | boolean | undefined, at: string): string {
    if (schema === undefined || schema === true) return 'unknown';
    if (schema === false) return 'never';
    for (const keyword of Object.keys(schema)) {
      if (!UNDERSTOOD.has(keyword) && !keyword.startsWith('x-')) {
        throw new Error(
          `${this.where}: ${at} uses \`${keyword}\`, which the generator cannot type`,
        );
      }
    }
    const type = this.bare(schema, at);
    return schema.nullable ? union([type, 'null']) : type;
  }

  private bare(schema: Schema, at: string): string {
    if (schema.$ref !== undefined) {
      if (!schema.$ref.startsWith(SCHEMA_REF)) {
        throw new Error(`${this.where}: ${at} refers to ${schema.$ref}, outside the components`);
      }
      const name = schema.$ref.slice(SCHEMA_REF.length);
      if (!(name in this.components)) throw new Error(`${this.where}: ${at} refers to ${name}`);
      this.refs.add(name);
      return name;
    }
    if (schema.not !== undefined) {
      // `{ not: {} }` matches nothing: a field that must be left out.
      if (Object.keys(schema.not).length === 0) return 'never';
      throw new Error(`${this.where}: ${at} uses \`not\` with a schema, which has no type`);
    }
    const choices = schema.anyOf ?? schema.oneOf;
    if (choices) return union(choices.map((choice, i) => grouped(this.type(choice, `${at}/${i}`))));
    if (schema.allOf) {
      return schema.allOf.map((part, i) => grouped(this.type(part, `${at}/${i}`))).join(' & ');
    }
    if ('const' in schema) return JSON.stringify(schema.const);
    if (schema.enum) return union(schema.enum.map((value) => JSON.stringify(value)));

    let types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
    if (types.length === 0) {
      if (schema.properties || schema.additionalProperties !== undefined) types = ['object'];
      else if (schema.items) types = ['array'];
      // A schema with no type and no shape takes any JSON value.
      else return 'unknown';
    }
    return union(types.map((type) => this.single(type, schema, at)));
  }

  private single(type: string, schema: Schema, at: string): string {
    switch (type) {
      case 'string':
        return 'string';
      case 'integer':
      case 'number':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'null':
        return 'null';
      case 'array':
        return `${grouped(this.type(schema.items, `${at}/items`))}[]`;
      case 'object':
        return this.object(schema, at);
      default:
        throw new Error(
          `${this.where}: ${at} has type \`${type}\`, which the generator cannot type`,
        );
    }
  }

  /** The members of an object type, one per line, each with its description. */
  members(schema: Schema, at: string): string[] {
    const required = new Set(schema.required ?? []);
    const lines = Object.entries(schema.properties ?? {}).map(([name, property]) => {
      const optional = required.has(name) ? '' : '?';
      const deprecated = property.deprecated ? '@deprecated' : undefined;
      return `${doc(property.description, deprecated)}${propertyKey(name)}${optional}: ${this.type(property, `${at}/${name}`)};`;
    });
    const extra = schema.additionalProperties;
    if (extra !== undefined && extra !== false) {
      lines.push(`[key: string]: ${this.type(extra, `${at}/additionalProperties`)};`);
    }
    return lines;
  }

  private object(schema: Schema, at: string): string {
    const hasProperties = Object.keys(schema.properties ?? {}).length > 0;
    const extra = schema.additionalProperties;
    if (!hasProperties) {
      if (extra === false) return 'Record<string, never>';
      return `Record<string, ${this.type(extra, `${at}/additionalProperties`)}>`;
    }
    if (extra !== undefined && extra !== false && extra !== true) {
      // An index signature has to admit every named property too, so the
      // two halves are written apart and joined.
      const named = this.members({ ...schema, additionalProperties: false }, at);
      return `{\n${named.join('\n')}\n} & Record<string, ${this.type(extra, `${at}/additionalProperties`)}>`;
    }
    return `{\n${this.members(schema, at).join('\n')}\n}`;
  }

  /**
   * A named export for a schema: an interface when it is a plain object, which
   * reads better in an editor's hover, and a type alias for anything else.
   */
  declaration(name: string, schema: Schema, comment: string): string {
    const plainObject =
      schema.$ref === undefined &&
      !schema.anyOf &&
      !schema.oneOf &&
      !schema.allOf &&
      !schema.nullable &&
      (schema.type === 'object' || (schema.type === undefined && schema.properties)) &&
      Object.keys(schema.properties ?? {}).length > 0 &&
      (schema.additionalProperties === undefined || schema.additionalProperties === false);
    if (plainObject) {
      this.type(schema, name); // checks every keyword, and collects references
      return `${comment}export interface ${name} {\n${this.members(schema, name).join('\n')}\n}\n`;
    }
    return `${comment}export type ${name} = ${this.type(schema, name)};\n`;
  }
}

interface Route {
  id: string;
  method: Method;
  path: string;
  operation: Operation;
  pathParams: Parameter[];
  query: Parameter[];
  body: { schema: Schema; required: boolean } | null;
  /** The JSON body of the success answer, or null when it has none (204). */
  response: Schema | null;
}

function routesOf(document: OpenApiDocument): Route[] {
  const routes: Route[] = [];
  const seen = new Set<string>();
  for (const [path, item] of Object.entries(document.paths)) {
    for (const [key, operation] of Object.entries(item)) {
      if (!(METHODS as readonly string[]).includes(key)) {
        if (['parameters', 'summary', 'description', 'servers'].includes(key)) {
          throw new Error(`${path} sets \`${key}\` for every method, which the generator ignores`);
        }
        throw new Error(`${path} has a \`${key}\` operation, which the client cannot send`);
      }
      const method = key as Method;
      const where = `${method.toUpperCase()} ${path}`;
      const id = operation.operationId;
      if (!id || !IDENTIFIER.test(id)) throw new Error(`${where} has no usable operationId`);
      if (seen.has(id)) throw new Error(`${where}: operationId ${id} is used twice`);
      seen.add(id);

      const parameters = operation.parameters ?? [];
      for (const parameter of parameters) {
        if (parameter.in !== 'path' && parameter.in !== 'query') {
          throw new Error(`${where}: a ${parameter.in} parameter cannot be sent by the client`);
        }
      }
      const pathParams = parameters.filter((parameter) => parameter.in === 'path');
      const named = [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
      const declared = pathParams.map((parameter) => parameter.name);
      if (named.join() !== declared.join()) {
        throw new Error(
          `${where}: the path names {${named.join('}, {')}} but declares ${declared}`,
        );
      }
      for (const name of declared) {
        if (name === 'query' || name === 'body' || !IDENTIFIER.test(name)) {
          throw new Error(`${where}: a path parameter cannot be called ${name}`);
        }
      }

      let body: Route['body'] = null;
      if (operation.requestBody) {
        const content = operation.requestBody.content ?? {};
        const json = content['application/json'];
        if (!json || Object.keys(content).length !== 1) {
          throw new Error(`${where} takes a body that is not JSON alone`);
        }
        body = { schema: json.schema ?? {}, required: operation.requestBody.required === true };
      }

      const successes = Object.entries(operation.responses ?? {}).filter(([code]) =>
        /^2\d\d$/.test(code),
      );
      if (successes.length === 0) throw new Error(`${where} has no success response`);
      const bodies = successes.map(([code, answer]) => {
        const content = answer.content ?? {};
        if (Object.keys(content).length === 0) return null;
        const json = content['application/json'];
        if (!json) throw new Error(`${where} answers ${code} with something other than JSON`);
        return json.schema ?? {};
      });
      if (bodies.length > 1) {
        throw new Error(
          `${where} has more than one success response, which the client cannot tell apart`,
        );
      }

      routes.push({
        id,
        method,
        path,
        operation,
        pathParams,
        query: parameters.filter((parameter) => parameter.in === 'query'),
        body,
        response: bodies[0] ?? null,
      });
    }
  }
  return routes;
}

function importLine(refs: Set<string>, from: string): string {
  if (refs.size === 0) return '';
  return `import type { ${[...refs].sort().join(', ')} } from '${from}';\n\n`;
}

function schemasFile(components: Record<string, Schema>): string {
  const emitter = new Emitter(components, 'components');
  const body = Object.entries(components)
    .map(([name, schema]) => emitter.declaration(name, schema, doc(schema.description)))
    .join('\n');
  return `${HEADER}\n${body}`;
}

function operationsFile(routes: Route[], components: Record<string, Schema>): string {
  const emitter = new Emitter(components, 'operations');
  const reserved = new Set(Object.keys(components));
  const claim = (name: string) => {
    if (reserved.has(name)) throw new Error(`Generated type ${name} would be declared twice`);
    reserved.add(name);
    return name;
  };

  const types: string[] = [];
  for (const route of routes) {
    const name = pascal(route.id);
    if (route.query.length > 0) {
      const lines = route.query.map((parameter) => {
        const optional = parameter.required ? '' : '?';
        const type = emitter.type(parameter.schema, `${route.id}/query/${parameter.name}`);
        return `${doc(parameter.description)}${propertyKey(parameter.name)}${optional}: ${type};`;
      });
      types.push(
        `${doc(`The query \`${route.id}\` takes.`)}export interface ${claim(`${name}Query`)} {\n${lines.join('\n')}\n}\n`,
      );
    }
    if (route.body) {
      types.push(
        emitter.declaration(
          claim(`${name}Body`),
          route.body.schema,
          doc(`The body \`${route.id}\` sends.`, route.body.schema.description),
        ),
      );
    }
    if (route.response) {
      types.push(
        emitter.declaration(
          claim(`${name}Response`),
          route.response,
          doc(`What \`${route.id}\` answers with.`, route.response.description),
        ),
      );
    }
  }

  const table = routes
    .map((route) => {
      const scopes = route.operation['x-storeware-scopes'] ?? [];
      return `${route.id}: { method: '${route.method.toUpperCase()}', path: '${route.path}', scopes: [${scopes.map((scope) => `'${scope}'`).join(', ')}] },`;
    })
    .join('\n');

  return `${HEADER}
${importLine(emitter.refs, './schemas')}${types.join('\n')}
/**
 * Every operation of the public API: its method, its path with \`{name}\` for
 * each path parameter, and the scopes an app needs to call it.
 */
export const operations = {
${table}
} as const;

export type OperationId = keyof typeof operations;
`;
}

/** The argument a client method takes, or null when it takes none. */
function inputOf(route: Route): { type: string; optional: boolean } | null {
  const name = pascal(route.id);
  const members = route.pathParams.map((parameter) => `${parameter.name}: string;`);
  let optional = route.pathParams.length === 0;
  if (route.query.length > 0) {
    const required = route.query.some((parameter) => parameter.required);
    members.push(`query${required ? '' : '?'}: ${name}Query;`);
    if (required) optional = false;
  }
  if (route.body) {
    members.push(`body${route.body.required ? '' : '?'}: ${name}Body;`);
    if (route.body.required) optional = false;
  }
  if (members.length === 0) return null;
  return { type: `{ ${members.join(' ')} }`, optional };
}

function apiFile(routes: Route[]): string {
  const imported = new Set<string>();
  const methods = routes.map((route) => {
    const name = pascal(route.id);
    if (route.query.length > 0) imported.add(`${name}Query`);
    if (route.body) imported.add(`${name}Body`);
    if (route.response) imported.add(`${name}Response`);
    const input = inputOf(route);
    const argument = input ? `input${input.optional ? '?' : ''}: ${input.type}` : '';
    const answer = route.response ? `${name}Response` : 'void';
    const scopes = route.operation['x-storeware-scopes'] ?? [];
    const needs =
      scopes.length > 0 ? `, with ${scopes.map((scope) => `\`${scope}\``).join(' and ')}` : '';
    const comment = doc(
      route.operation.summary ? `${route.operation.summary.replace(/\.$/, '')}.` : undefined,
      route.operation.description,
      `\`${route.method.toUpperCase()} ${route.path}\`${needs}.`,
      route.operation.deprecated ? '@deprecated' : undefined,
    );
    return `${comment}${route.id}(${argument}): Promise<${answer}>;`;
  });
  const implementations = routes.map((route) => `${route.id}: call('${route.id}'),`);

  return `${HEADER}
import { operations, type OperationId } from './operations';
${imported.size > 0 ? `import type { ${[...imported].sort().join(', ')} } from './operations';` : ''}

/**
 * What the typed client sends its requests through.
 *
 * A \`StorewareClient\` is one: it adds the shop's token, rotates it when it
 * runs out, and turns an error answer into a \`StorewareApiError\`. Each path
 * arrives with its parameters encoded and its query string attached.
 */
export interface ApiTransport {
  get<T>(path: string): Promise<T>;
  post<T>(path: string, body?: unknown): Promise<T>;
  put<T>(path: string, body?: unknown): Promise<T>;
  patch<T>(path: string, body?: unknown): Promise<T>;
  delete<T>(path: string, body?: unknown): Promise<T>;
}

/** One method for each operation of the public API, named by its operationId. */
export interface ApiClient {
${methods.join('\n\n')}
}

type Route = (typeof operations)[OperationId];

/**
 * Fills in the path, attaches the query, and sends the body with the route's
 * method. Async so that a missing parameter is a rejected promise, like every
 * other way a call can fail, rather than a throw before there is one.
 */
async function send<T>(transport: ApiTransport, route: Route, input: Record<string, unknown>): Promise<T> {
  const path = route.path.replace(/\\{(\\w+)\\}/g, (_, name: string) => {
    const value = input[name];
    if (value === undefined || value === null || value === '') {
      throw new TypeError(\`\${route.method} \${route.path} needs \${name}\`);
    }
    return encodeURIComponent(String(value));
  });

  const search = new URLSearchParams();
  const query = (input['query'] ?? {}) as Record<string, unknown>;
  for (const [key, value] of Object.entries(query)) {
    if (value === undefined) continue;
    for (const one of Array.isArray(value) ? value : [value]) search.append(key, String(one));
  }
  const encoded = search.toString();
  const target = encoded ? \`\${path}?\${encoded}\` : path;

  const body = input['body'];
  switch (route.method) {
    case 'GET':
      return transport.get<T>(target);
    case 'POST':
      return transport.post<T>(target, body);
    case 'PUT':
      return transport.put<T>(target, body);
    case 'PATCH':
      return transport.patch<T>(target, body);
    case 'DELETE':
      return transport.delete<T>(target, body);
  }
}

/**
 * A typed client for the public API, sending through \`transport\`.
 *
 * \`\`\`ts
 * const api = createApiClient(await app.clientFor(storeId));
 * const { data } = await api.listProducts({ storeId, query: { status: 'active' } });
 * \`\`\`
 */
export function createApiClient(transport: ApiTransport): ApiClient {
  const call =
    (id: OperationId) =>
    <T>(input: object = {}): Promise<T> =>
      send<T>(transport, operations[id], input as Record<string, unknown>);

  return {
${implementations.join('\n')}
  };
}
`;
}

function indexFile(): string {
  return `${HEADER}
export * from './schemas';
export * from './operations';
export * from './api';
`;
}

/**
 * The generated files, by name, before formatting. Pure: the same document
 * always gives the same text, and nothing is read or written.
 */
export function generateClient(document: OpenApiDocument): Record<string, string> {
  if (!document.openapi?.startsWith('3.')) {
    throw new Error(`Expected an OpenAPI 3 document, got ${document.openapi}`);
  }
  const components = document.components?.schemas ?? {};
  const routes = routesOf(document);
  return {
    'schemas.ts': schemasFile(components),
    'operations.ts': operationsFile(routes, components),
    'api.ts': apiFile(routes),
    'index.ts': indexFile(),
  };
}

/** The generated files as they are committed: formatted by prettier with the repository's settings. */
export async function generateFormatted(
  document: OpenApiDocument,
): Promise<Record<string, string>> {
  const prettier = await import('prettier');
  const files = generateClient(document);
  const formatted: Record<string, string> = {};
  for (const [name, source] of Object.entries(files)) {
    const filepath = join(OUTPUT_DIR, name);
    const options = (await prettier.resolveConfig(filepath)) ?? {};
    formatted[name] = await prettier.format(source, { ...options, filepath });
  }
  return formatted;
}

export function readDocument(): OpenApiDocument {
  return JSON.parse(readFileSync(DOCUMENT_PATH, 'utf8')) as OpenApiDocument;
}

async function main(): Promise<void> {
  const files = await generateFormatted(readDocument());
  mkdirSync(OUTPUT_DIR, { recursive: true });
  for (const [name, contents] of Object.entries(files)) {
    writeFileSync(join(OUTPUT_DIR, name), contents);
  }
  const lines = Object.values(files).reduce((sum, text) => sum + text.split('\n').length, 0);
  console.warn(`Wrote ${Object.keys(files).length} files, ${lines} lines, to ${OUTPUT_DIR}`);
}

const invokedAs = process.argv[1];
if (invokedAs && import.meta.url === pathToFileURL(invokedAs).href) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
